"""模型漆色号种子数据。

数据契约
--------
每条记录是 8 元组（旧格式，仍然合法）或 12 元组（新格式，带溯源）：

    (code, 中文名, 英文名, hex, finish, opacity, standards, note)
    (code, 中文名, 英文名, hex, finish, opacity, standards, note,
     src_kind, src_ref, src_date, src_confidence)

* ``finish``   : gloss 光泽 / semi 半光泽 / flat 消光 / metal 金属 /
                 pearl 珠光 / clear 透明 / fluor 荧光
* ``opacity``  : opaque 不透明 / semi 半透明 / clear 透明
* ``standards``: 关联的标准色号，多个用 ``;`` 分隔（FS / RAL / RLM / BS），
                 这是跨品牌「替代色号」的主要依据
* ``hex``      : 数字化近似色值。来源是官方色卡的屏幕取色 + 标准色的公开
                 色度数据，用于**相对匹配**，不等同于实干漆膜。用户可在
                 「校准」里覆盖。
* ``src_kind`` : official / standard / retail / chart / derived / calibrated
* ``src_ref``  : 来源 ID，必须在 ``app/data/sources.py`` 的 SOURCES 中存在
* ``src_date`` : YYYY-MM，采集时间
* ``src_confidence``: 0-1，留空则取该 kind 的默认置信度

补齐 672 条溯源的正确做法**不是**改这里，而是往 ``sources.ENTRY_SOURCES``
里按 uid 加标注 —— 那个表小、好审、改错了不影响种子数据。本表保留 12 元组
格式只是为了将来逐条内联。

**8 元组一律按「未标注」处理**（derived + 空引用），置信度压到最低档。
未标注不等于可信，这一点不能含糊。

数据完整性由 ``scripts/check_paint_db.py`` 校验（重复色号、非法 hex、
缺失字段会直接报错）。
"""

